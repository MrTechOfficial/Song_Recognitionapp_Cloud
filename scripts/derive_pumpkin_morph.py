"""Extract fold-free radial warp patches from the original painted faces.

Reads PNGs; writes Dart geometry only. Each eye and mouth uses the same radial
mesh topology, with a fixed outer frame. Matching angular rays prevent the
crossed/sliver triangles of an unconstrained whole-face triangulation.
"""
from pathlib import Path
import math
import cv2
import numpy as np

PROJECT = Path(__file__).resolve().parents[1]
ROOT = PROJECT / 'assets/seasonal/halloween_v2'


def cross(a, b):
    return a[0] * b[1] - a[1] * b[0]


def patch(mask, box, count):
    x0, y0, x1, y1 = box
    region = np.zeros_like(mask)
    region[y0:y1, x0:x1] = mask[y0:y1, x0:x1]
    paths, _ = cv2.findContours(region, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    contour = max(paths, key=cv2.contourArea)[:, 0, :].astype(float)
    filled = np.zeros_like(mask)
    cv2.drawContours(filled, [contour.astype('int32')], -1, 255, -1)
    distance = cv2.distanceTransform(filled, cv2.DIST_L2, 5)
    yy, xx = np.mgrid[:mask.shape[0], :mask.shape[1]]
    mean = contour.mean(axis=0)
    score = distance - np.hypot(xx - mean[0], yy - mean[1]) * .12
    y, x = np.unravel_index(np.argmax(score), score.shape)
    center = np.array([x, y], dtype=float)
    edge, frame = [], []
    for index in range(count):
        angle = -math.pi / 2 + index * math.pi * 2 / count
        direction = np.array([math.cos(angle), math.sin(angle)])
        hits = []
        for first, second in zip(contour, np.roll(contour, -1, axis=0)):
            segment = second - first
            denominator = cross(direction, segment)
            if abs(denominator) < 1e-9:
                continue
            radius = cross(first - center, segment) / denominator
            along = cross(first - center, direction) / denominator
            if radius >= 0 and 0 <= along <= 1:
                hits.append(radius)
        radius = max(hits) if hits else .25
        candidates = []
        if direction[0] > 1e-9: candidates.append((x1 - center[0]) / direction[0])
        if direction[0] < -1e-9: candidates.append((x0 - center[0]) / direction[0])
        if direction[1] > 1e-9: candidates.append((y1 - center[1]) / direction[1])
        if direction[1] < -1e-9: candidates.append((y0 - center[1]) / direction[1])
        outer = min(candidates)
        assert outer > radius, (box, index, outer, radius)
        edge.append(center + direction * radius)
        frame.append(center + direction * outer)
    return np.vstack([center, edge, frame])


faces, indices = [], []
parts = [((24, 28, 56, 57), 32), ((65, 28, 102, 57), 32), ((25, 58, 101, 86), 48)]
for name in ['classic', 'surprised', 'sly']:
    a = cv2.imread(str(ROOT / f'pumpkin_{name}.png'), cv2.IMREAD_UNCHANGED)
    b, g, r = [a[:, :, i].astype(float) for i in range(3)]
    y, x = np.mgrid[:a.shape[0], :a.shape[1]]
    mask = (((g > 132) & (r > 180) & (g - b > 48) &
             (x > 23) & (x < 100) & (y > 28) & (y < 84)) * 255).astype('uint8')
    landmarks = []
    for box, count in parts:
        points = patch(mask, box, count)
        if name == 'classic':
            offset = len(landmarks)
            for i in range(count):
                following = (i + 1) % count
                inner, next_inner = offset + 1 + i, offset + 1 + following
                outer, next_outer = inner + count, next_inner + count
                indices.extend([offset, inner, next_inner,
                                inner, outer, next_inner,
                                next_inner, outer, next_outer])
        landmarks.extend(points)
    faces.append(np.array(landmarks))

# Verify every tweened pose, not just the endpoints. Radial rings remain ordered
# and all triangles keep their orientation throughout all three expressions.
triangles = np.array(indices).reshape(-1, 3)
for first, second in [(0, 1), (0, 2), (1, 2)]:
    for phase in np.linspace(0, 1, 101):
        points = (faces[first] * (1 - phase) + faces[second] * phase)[triangles]
        a, b = points[:, 1] - points[:, 0], points[:, 2] - points[:, 0]
        area = a[:, 0] * b[:, 1] - a[:, 1] * b[:, 0]
        assert np.all(area > 0), (first, second, phase, area.min())
text = ["// Generated by scripts/derive_pumpkin_morph.py. Fixed-topology radial patches.",
        "import 'dart:ui';", "", "class HalloweenCarvings {",
        "  static const landmarks = <List<Offset>>["]
for name, points in zip(['classic', 'surprised', 'sly'], faces):
    text += [f'    // {name}: left eye, right eye, mouth.', '    [']
    text += [f'      Offset({x:.5f}, {y:.5f}),' for x, y in points]
    text += ['    ],']
text += ['  ];', '  static const indices = <int>[']
for start in range(0, len(indices), 24):
    text += ['    ' + ', '.join(map(str, indices[start:start + 24])) + ',']
text += ['  ];', '}']
(PROJECT / 'lib/seasonal/halloween_carvings.dart').write_text('\n'.join(text) + '\n')
print(f'Derived three painted faces: {len(faces[0])} landmarks, {len(triangles)} fold-free triangles per pose.')
